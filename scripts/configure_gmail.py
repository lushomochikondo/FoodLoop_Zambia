"""Private, local Gmail setup. Authenticate only; this script never sends email."""
import getpass
import json
import os
import queue
import re
import smtplib
import ssl
import subprocess
import tempfile
import threading
import tkinter as tk
import webbrowser
from datetime import datetime, timezone
from pathlib import Path
from tkinter import messagebox, ttk
from dotenv import dotenv_values

ROOT=Path(__file__).resolve().parent.parent

def save_configuration(email,password):
    with smtplib.SMTP('smtp.gmail.com',587,timeout=15) as smtp:
        smtp.ehlo()
        smtp.starttls(context=ssl.create_default_context())
        smtp.ehlo()
        smtp.login(email,password)
    # Protect a temporary file before writing credentials; atomically replace .env.
    fd,name=tempfile.mkstemp(dir=ROOT,prefix='.gmail-env-',suffix='.tmp')
    os.close(fd)
    temporary=Path(name)
    try:
        if os.name=='nt':
            subprocess.run(['icacls',str(temporary),'/inheritance:r','/grant:r',f'{getpass.getuser()}:(F)'],check=True,capture_output=True,creationflags=subprocess.CREATE_NO_WINDOW)
        else: temporary.chmod(0o600)
        target=ROOT/'.env'
        values={'EMAIL_NOTIFICATIONS_ENABLED':'1','EMAIL_BACKEND':'django.core.mail.backends.smtp.EmailBackend','EMAIL_HOST':'smtp.gmail.com','EMAIL_PORT':'587','EMAIL_USE_TLS':'1','EMAIL_USE_SSL':'0','EMAIL_HOST_USER':email,'EMAIL_HOST_PASSWORD':password,'DEFAULT_FROM_EMAIL':f'FoodLoop Zambia <{email}>'}
        config=dict(dotenv_values(target,interpolate=False)) if target.exists() else {}
        config.update(values)
        def quoted(value): return str(value or '').replace('\\','\\\\').replace("'","\\'")
        temporary.write_text(''.join(f"{key}='{quoted(value)}'\n" for key,value in config.items()),encoding='utf-8')
        os.replace(temporary,target)
        (ROOT/'gmail_setup.status.json').write_text(json.dumps({'configured':True,'enabled':True,'verified_at':datetime.now(timezone.utc).isoformat()}))
    finally:
        if temporary.exists(): temporary.unlink()

def main():
    root=tk.Tk()
    root.title('FoodLoop — Connect Gmail')
    root.geometry('640x720')
    root.minsize(600,680)
    root.configure(bg='#f7f8f3')
    frame=ttk.Frame(root,padding=28);frame.pack(fill='both',expand=True)
    ttk.Label(frame,text='Connect FoodLoop to Gmail',font=('Segoe UI',20,'bold')).pack(anchor='w',pady=(0,12))
    ttk.Label(frame,text='1. Sign in to Google and turn on 2-Step Verification.\n2. Create an app password named FoodLoop.\n3. Enter your Gmail address and that app password below.',wraplength=540).pack(anchor='w',pady=(0,15))
    ttk.Button(frame,text='Step 1: Open Google 2-Step Verification',command=lambda:webbrowser.open('https://myaccount.google.com/signinoptions/two-step-verification')).pack(anchor='w',pady=(0,10))
    ttk.Button(frame,text='Step 2: Create a Google App Password',command=lambda:webbrowser.open('https://myaccount.google.com/apppasswords')).pack(anchor='w',pady=(0,18))
    ttk.Label(frame,text='Gmail sender address').pack(anchor='w')
    email=ttk.Entry(frame,font=('Segoe UI',12));email.pack(fill='x',pady=(6,16))
    ttk.Label(frame,text='16-character app password (hidden)').pack(anchor='w')
    password=ttk.Entry(frame,show='*',font=('Segoe UI',12));password.pack(fill='x',pady=(6,16))
    ttk.Label(frame,text='Saving enables queued email updates for registered users who have email updates turned on. This setup checks authentication only; it does not send a test email.',wraplength=490).pack(anchor='w',pady=(0,14))
    status=tk.StringVar(value='Credentials stay in your local, Git-ignored .env file.')
    ttk.Label(frame,textvariable=status,wraplength=490).pack(anchor='w',pady=(0,14))
    results=queue.Queue()
    def worker(address,secret):
        try: save_configuration(address,secret)
        except Exception: results.put(False)
        else: results.put(True)
    def save():
        address=email.get().strip()
        secret=''.join(password.get().split())
        if not re.fullmatch(r'[^\s@]+@[^\s@]+\.[^\s@]+',address):
            messagebox.showerror('Check email','Enter the Gmail address you want FoodLoop to send from.');return
        if len(secret)!=16 or not secret.isalnum():
            messagebox.showerror('Check app password','Use the 16-character app password generated by Google.');return
        button.configure(state='disabled');status.set('Checking Gmail over TLS…')
        threading.Thread(target=worker,args=(address,secret),daemon=True).start()
    def poll():
        try: result=results.get_nowait()
        except queue.Empty: root.after(150,poll);return
        if result:
            password.delete(0,'end')
            status.set('Gmail authenticated and settings saved. Tell Codex the setup is complete so the notification worker can start.')
            messagebox.showinfo('Gmail connected','Gmail is authenticated. No email was sent.\n\nTell Codex: Gmail setup is complete.')
        else:
            status.set('Could not finish setup. Check Gmail address, app password, internet connection and local file permissions.')
            button.configure(state='normal')
        root.after(150,poll)
    button=ttk.Button(frame,text='Verify, save and enable Gmail notifications',command=save);button.pack(fill='x')
    root.after(150,poll)
    email.focus()
    root.mainloop()

if __name__=='__main__': main()
